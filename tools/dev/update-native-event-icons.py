"""Refresh the native calendar's small subset of Flutter's existing icon font.

Usage: python tools/dev/update-native-event-icons.py <flutter-sdk>
Uses Flutter's bundled font-subset executable; no Python packages are required.
"""
from pathlib import Path
import re
import subprocess
import sys

repo = Path(__file__).resolve().parents[2]
sdk = Path(sys.argv[1])
registry = (repo / "lib/features/shared/icon_picker.dart").read_text(encoding="utf-8")
icons = (sdk / "packages/flutter/lib/src/material/icons.dart").read_text(encoding="utf-8")
names = dict(re.findall(r"'([^']+)': Icons\.(\w+)", registry))
names["__event"] = "event_outlined"
glyphs = {key: int(re.search(rf"static const IconData {name} = IconData\((0x[0-9a-f]+),", icons)[1], 16)
          for key, name in names.items()}
output = repo / "experiments/widget-shell-probe/Icons"
output.mkdir(exist_ok=True)
fonts = sdk / "bin/cache/artifacts/material_fonts"
subprocess.run([str(sdk / "bin/cache/artifacts/engine/windows-x64/font-subset.exe"),
                str(output / "event-icons.otf"), str(fonts / "materialicons-regular.otf")],
               input=" ".join(map(str, glyphs.values())) + "\n", text=True, check=True)
(output / "LICENSE.txt").write_text(
    "Material Icons by Google\n"
    "Source: https://github.com/google/material-design-icons\n"
    "Modified: a 31-glyph subset for Todorbit's native calendar, taken from the\n"
    "Material Icons font distributed with the Flutter SDK. Glyph artwork is unchanged.\n"
    "License supplied with that font: Creative Commons Attribution 4.0 International\n"
    "https://creativecommons.org/licenses/by/4.0/\n\n"
    + (fonts / "materialicons_license.txt").read_text(encoding="utf-8"), encoding="utf-8")
entries = "\n".join(f'        ["{key}"] = "\\U{code:08x}",' for key, code in glyphs.items())
(output / "EventIconGlyphs.cs").write_text(
    "// Generated by tools/dev/update-native-event-icons.py from the Flutter icon registry.\n"
    "internal static class EventIconGlyphs\n{\n"
    "    internal static readonly IReadOnlyDictionary<string, string> Values = new Dictionary<string, string>\n"
    "    {\n" + entries + "\n    };\n}\n", encoding="utf-8")
print(f"Generated {len(glyphs)} glyphs, {(output / 'event-icons.otf').stat().st_size} font bytes")
